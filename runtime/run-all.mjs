// Runs the runtime smoke test across whatever runtimes are installed, prints a
// matrix, and writes reports/runtime-report.md (the committed source of truth).
// Missing runtimes are skipped (not failed). Run: npm run smoke

import { spawnSync, execSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { resolvedVersion, reportDir } from "../lib/versions.mjs";

const candidate = resolvedVersion("candidate");
const outDir = reportDir();

const dir = import.meta.dirname;
const root = join(dir, "..");
const has = (cmd) => {
  try {
    execSync(`command -v ${cmd}`, { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
};
const hasWrangler = existsSync(join(root, "node_modules", "wrangler"));

const CHECKS = [
  "keypair: random + sign + verify",
  "strkey: encode/decode round-trip",
  "hash: sha256 of bytes",
  "tx: build + sign + toXDR",
];

const runners = [
  { name: "Node", cmd: "node", args: [join(dir, "run-node.mjs")], available: true, desc: "reference runtime" },
  {
    name: "Browser (simulated)",
    cmd: "node",
    args: [join(dir, "run-browser.mjs")],
    available: true,
    desc: "Node with the `Buffer` global removed — NOT a real browser; runs via inlined `buffer` shim",
  },
  { name: "Bun", cmd: "bun", args: ["run", join(dir, "run-bun.mjs")], available: has("bun"), desc: "" },
  {
    name: "Deno",
    cmd: "deno",
    args: ["run", "--allow-read", "--allow-env", "--allow-net", join(dir, "run-deno.mjs")],
    available: has("deno"),
    desc: "resolves `npm:@stellar/stellar-sdk` via node-compat",
  },
  {
    name: "Cloudflare Workers",
    cmd: "node",
    args: [join(dir, "run-worker.mjs")],
    available: hasWrangler,
    desc: "`workerd`, `nodejs_compat` deliberately off",
    note: "needs `wrangler` (npm i -D wrangler)",
  },
];

const results = [];
for (const r of runners) {
  if (!r.available) {
    console.log(`\n[${r.name}] skipped — ${r.note ?? "runtime not installed"}`);
    results.push({ name: r.name, status: "skipped", desc: r.note ?? r.desc });
    continue;
  }
  const out = spawnSync(r.cmd, r.args, {
    encoding: "utf8",
    timeout: 120000,
    maxBuffer: 10 * 1024 * 1024,
  });
  const timedOut = out.error?.code === "ETIMEDOUT" || out.signal != null;
  const text = `${out.stdout ?? ""}${out.stderr ?? ""}${timedOut ? "\n[runner timed out after 120s]" : ""}`;
  process.stdout.write(text);
  results.push({
    name: r.name,
    status: out.status === 0 ? "pass" : "fail",
    desc: r.desc,
    output: text.trim(),
  });
}

// --- Report --------------------------------------------------------------
const sym = { pass: "✅", fail: "❌", skipped: "⏭️" };
const lines = [];
lines.push(`# Runtime compatibility report: \`@stellar/stellar-sdk\` ${candidate}`);
lines.push("");
const today = new Date().toISOString().slice(0, 10);
lines.push(
  `Generated by \`npm run smoke\` on ${today}. Each runtime runs the same operations ` +
    `against the candidate (\`@stellar/stellar-sdk@${candidate}\`), with **no polyfills ` +
    "installed**, so a missing global fails loudly rather than hiding.",
);
lines.push("");
lines.push("Checks run in every runtime:");
lines.push("");
for (const c of CHECKS) lines.push(`- ${c}`);
lines.push("");
lines.push("| Runtime | Result | Notes |");
lines.push("| --- | --- | --- |");
for (const r of results) {
  lines.push(`| ${r.name} | ${sym[r.status] ?? ""} ${r.status} | ${r.desc ?? ""} |`);
}
lines.push("");
lines.push("## Caveats");
lines.push("");
lines.push(
  "- **Scope:** these four checks exercise crypto + XDR primitives only. They do NOT " +
    "exercise Horizon HTTP, RPC, or SSE streaming. A green row means the core primitives " +
    "work on that runtime, not that every SDK feature does.",
);
lines.push(
  '- **"Browser (simulated)" is not a real browser** — it is Node with the `Buffer` ' +
    "global deleted, which tests whether v16 stands alone without that global. A headless-" +
    "browser (Playwright) run would be stronger.",
);
lines.push(
  "- The browser and Cloudflare Workers passes rely on the bundler inlining a `buffer` " +
    "shim. They run, but this is not yet \"zero-dependency, no polyfills.\"",
);
lines.push(
  "- Skipped runtimes are not failures — install them to fill in the matrix (`bun`, " +
    "`deno`, or `npm i -D wrangler`).",
);
lines.push("");
lines.push("## Raw output");
lines.push("");
for (const r of results) {
  if (r.status === "skipped") continue;
  lines.push(`### ${r.name}`);
  lines.push("");
  lines.push("```");
  lines.push(r.output || "(no output)");
  lines.push("```");
  lines.push("");
}
writeFileSync(join(outDir, "runtime-report.md"), lines.join("\n") + "\n");

console.log("\n=== Runtime matrix ===");
for (const r of results) console.log(`  ${r.name.padEnd(24)} ${r.status}`);
console.log(`\nReport written to ${relative(process.cwd(), join(outDir, "runtime-report.md"))}`);

process.exit(results.some((r) => r.status === "fail") ? 1 : 0);
