// Bundle-size + tree-shaking benchmark for @stellar/stellar-sdk.
//
// For each scenario it bundles a fixture with esbuild (production settings),
// then records raw / gzip / brotli sizes and which "watched" dependencies
// actually landed in the bundle. Results are written to reports/bundle-report.md
// (the committed performance report) and printed to the console.
//
// Run: npm run benchmark

import { build, version as esbuildVersion } from "esbuild";
import { gzipSync, brotliCompressSync } from "node:zlib";
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const metaDir = join(root, "reports", "meta");
mkdirSync(metaDir, { recursive: true });

// Each scenario maps to two fixtures: <key>.v15.js and <key>.v16.js
const SCENARIOS = [
  { key: "full", label: "Full SDK (`import * as`)" },
  { key: "rpc-only", label: "RPC only (`/rpc`)" },
  { key: "horizon-classic", label: "Classic Horizon app" },
  { key: "contract", label: "Contract client (`/contract`)" },
];

const VERSIONS = ["v15", "v16"];

// If these show up in a narrow import, tree-shaking left something behind.
// (eventsource + smol-toml are Horizon-only; axios/feaxios back the HTTP client;
//  buffer is the polyfill the roadmap's M7 still needs to remove.)
const WATCH = ["eventsource", "smol-toml", "axios", "feaxios", "buffer"];

const kb = (bytes) => (bytes / 1024).toFixed(1) + " KB";

async function measure(scenarioKey, version) {
  const entry = join(root, "fixtures", `${scenarioKey}.${version}.js`);
  try {
    const result = await build({
      entryPoints: [entry],
      bundle: true,
      minify: true,
      format: "esm",
      platform: "browser",
      target: "es2022",
      metafile: true,
      write: false,
      legalComments: "none",
      logLevel: "silent",
    });
    const out = result.outputFiles[0].contents;
    writeFileSync(
      join(metaDir, `${scenarioKey}.${version}.json`),
      JSON.stringify(result.metafile, null, 2),
    );
    const inputs = Object.keys(result.metafile.inputs);
    const watch = Object.fromEntries(
      // exact package-dir match (`/axios/`), not substring, to avoid e.g.
      // `some-axios-wrapper` registering as `axios`.
      WATCH.map((w) => [w, inputs.some((p) => p.includes(`/${w}/`))]),
    );
    return {
      ok: true,
      raw: out.byteLength,
      gzip: gzipSync(out).byteLength,
      brotli: brotliCompressSync(out).byteLength,
      modules: inputs.length,
      watch,
    };
  } catch (err) {
    return { ok: false, error: err.message?.split("\n")[0] ?? String(err) };
  }
}

// Control: bundle a version's `full` fixture from its SOURCE entry, not v15's
// prebuilt `browser` UMD. `platform: node` + module/main mainFields skips the
// browser field; node built-ins stay external. This lets us compare v15 source
// to v16 source and separate "v16 ships less code" from "v15 shipped an
// un-tree-shakeable UMD bundle".
async function measureSource(scenarioKey, version) {
  const entry = join(root, "fixtures", `${scenarioKey}.${version}.js`);
  try {
    const result = await build({
      entryPoints: [entry],
      bundle: true,
      minify: true,
      format: "esm",
      platform: "node",
      mainFields: ["module", "main"],
      conditions: ["import", "module", "node", "default"],
      target: "es2022",
      write: false,
      legalComments: "none",
      logLevel: "silent",
    });
    const out = result.outputFiles[0].contents;
    return { ok: true, gzip: gzipSync(out).byteLength, raw: out.byteLength };
  } catch (err) {
    return { ok: false, error: err.message?.split("\n")[0] ?? String(err) };
  }
}

const results = {};
for (const s of SCENARIOS) {
  results[s.key] = {};
  for (const v of VERSIONS) {
    results[s.key][v] = await measure(s.key, v);
  }
}
const CONTROL_KEYS = ["full", "horizon-classic"];
const control = {};
for (const k of CONTROL_KEYS) {
  control[k] = { v15: await measureSource(k, "v15"), v16: await measureSource(k, "v16") };
}

// --- Build the markdown report -------------------------------------------

const lines = [];
lines.push("# Bundle-size report: `@stellar/stellar-sdk` v16-rc vs v15");
lines.push("");
const today = new Date().toISOString().slice(0, 10);
lines.push(
  `Generated by \`npm run benchmark\` on ${today} (Node ${process.version}, esbuild ${esbuildVersion}). ` +
    "Sizes are of a production esbuild bundle (minified, ESM, `platform: browser`). " +
    "gzip is the number users download; it is the one to quote.",
);
lines.push("");
lines.push("## Size by scenario");
lines.push("");
lines.push("| Scenario | v15 gzip | v16 gzip | Δ gzip | v16 brotli | v16 raw |");
lines.push("| --- | --- | --- | --- | --- | --- |");
for (const s of SCENARIOS) {
  const a = results[s.key].v15;
  const b = results[s.key].v16;
  if (!a.ok || !b.ok) {
    const why = !a.ok ? `v15: ${a.error}` : `v16: ${b.error}`;
    lines.push(`| ${s.label} | — | — | build failed (${why}) | — | — |`);
    continue;
  }
  const deltaNum = ((b.gzip - a.gzip) / a.gzip) * 100;
  const sign = deltaNum > 0 ? "+" : "";
  lines.push(
    `| ${s.label} | ${kb(a.gzip)} | ${kb(b.gzip)} | ${sign}${deltaNum.toFixed(1)}% | ${kb(b.brotli)} | ${kb(b.raw)} |`,
  );
}
lines.push("");
lines.push(
  "Negative Δ means v16 is smaller. **These are default-resolution numbers:** a bundler " +
    "resolves v15's root import to its prebuilt `browser` UMD bundle (which cannot be " +
    "tree-shaken) and v16 to ESM source, so the `full` / `horizon-classic` deltas mix a " +
    "real code-size win with that build-input difference. The `/rpc` and `/contract` rows " +
    "have v15 also resolve source (v15 CJS, v16 ESM). The control below isolates the " +
    "real difference.",
);
lines.push("");

// --- Control: source-to-source -------------------------------------------
const pctSmaller = (v15g, v16g) => ((v15g - v16g) / v15g) * 100;
const okScenario = (k) => results[k].v15.ok && results[k].v16.ok;
const range = (keys) => {
  const r = keys.filter(okScenario).map((k) => pctSmaller(results[k].v15.gzip, results[k].v16.gzip));
  return r.length ? [Math.min(...r), Math.max(...r)] : null;
};
const sub = range(["rpc-only", "contract"]);
const rootR = range(["full", "horizon-classic"]);

lines.push("## Build-input fairness (control: bundle from source)");
lines.push("");
lines.push(
  "v15 has no root ESM build, so its default root import resolves a prebuilt `browser` UMD " +
    "bundle that can't be tree-shaken. Re-bundling each version from its **source** entry " +
    "(v15 CJS via `main`, v16 ESM via `module`) isolates the real code-size difference. " +
    "These control builds use `platform: node` (node built-ins external), so they are NOT " +
    "directly comparable to the `platform: browser` rows above — compare v15-source to " +
    "v16-source *within* this table.",
);
lines.push("");
lines.push("| Scenario | v15 default (UMD) | v15 source (CJS) | v16 source (ESM) | v16 vs v15 source |");
lines.push("| --- | --- | --- | --- | --- |");
const ctlDelta = {};
for (const k of CONTROL_KEYS) {
  const def = results[k].v15;
  const c = control[k];
  if (!c.v15.ok || !c.v16.ok) {
    lines.push(`| ${k} | ${def?.ok ? kb(def.gzip) : "—"} | control build failed | — | — |`);
    continue;
  }
  ctlDelta[k] = pctSmaller(c.v15.gzip, c.v16.gzip);
  lines.push(
    `| ${k} | ${def?.ok ? kb(def.gzip) : "—"} | ${kb(c.v15.gzip)} | ${kb(c.v16.gzip)} | ${ctlDelta[k].toFixed(0)}% |`,
  );
}
lines.push("");
lines.push(
  "**Summary:** bundled from source (v15 CJS vs v16 ESM), v16 is " +
    `${ctlDelta["full"] != null ? `**${ctlDelta["full"].toFixed(0)}% smaller**` : "n/a"} for the full SDK and ` +
    `${ctlDelta["horizon-classic"] != null ? `**${ctlDelta["horizon-classic"].toFixed(0)}% smaller**` : "n/a"} for a classic Horizon import. ` +
    `Subpath imports (\`/rpc\`, \`/contract\`) show ${sub ? `${sub[0].toFixed(0)}–${sub[1].toFixed(0)}%` : "n/a"} smaller. ` +
    `The larger ${rootR ? `~${rootR[1].toFixed(0)}%` : ""} for default root imports also reflects v15 ` +
    "shipping a non-tree-shakeable UMD bundle, not only less code in v16.",
);
lines.push("");

lines.push("## Tree-shaking watch");
lines.push("");
lines.push(
  "Does a narrow import still drag in heavy or Horizon-only deps? A ✓ in a " +
    "non-full scenario means tree-shaking left that module in.",
);
lines.push("");
lines.push("| Scenario | version | " + WATCH.join(" | ") + " |");
lines.push("| --- | --- | " + WATCH.map(() => "---").join(" | ") + " |");
for (const s of SCENARIOS) {
  for (const v of VERSIONS) {
    const r = results[s.key][v];
    if (!r.ok) {
      lines.push(`| ${s.label} | ${v} | ${WATCH.map(() => "—").join(" | ")} |`);
      continue;
    }
    const cells = WATCH.map((w) => (r.watch[w] ? "✓" : "·")).join(" | ");
    lines.push(`| ${s.label} | ${v} | ${cells} |`);
  }
}
lines.push("");
lines.push(
  "Takeaway: v16's tree-shaking is real (Horizon-only `eventsource`/`smol-toml` drop out " +
    "of narrow imports) but not yet clean — the HTTP client (`feaxios`) and a `buffer` shim " +
    "still ride along in every v16 bundle.",
);
lines.push("");
lines.push("## Caveats");
lines.push("");
lines.push(
  "- Each version is resolved the way a real bundler would resolve it (default " +
    "export conditions). v16 resolves ESM source; v15's **root** import resolves " +
    "its `browser` field, a prebuilt UMD bundle — which is why v15 `full` and " +
    "`horizon-classic` are an identical ~273 KB (no tree-shaking) and the v15 " +
    "watch row shows nothing (esbuild can't see module names inside the prebuilt " +
    "bundle). v15 subpaths (`/rpc`, `/contract`) have no `browser` field and do " +
    "resolve source. This is the honest user-facing number, not a forced " +
    "same-entry comparison — but treat the v15 watch column as unreliable.",
);
lines.push(
  "- `platform: browser`. A scenario that fails to bundle shows a failure row in the " +
    "size table above, and is itself a finding (it needs polyfills in the browser).",
);
lines.push("");

const report = lines.join("\n") + "\n";
writeFileSync(join(root, "reports", "bundle-report.md"), report);

// --- Console summary ------------------------------------------------------

console.log("\nBundle-size benchmark\n=====================");
for (const s of SCENARIOS) {
  const a = results[s.key].v15;
  const b = results[s.key].v16;
  if (!a.ok || !b.ok) {
    console.log(`${s.label.padEnd(28)} build failed`);
    continue;
  }
  const delta = (((b.gzip - a.gzip) / a.gzip) * 100).toFixed(1);
  console.log(
    `${s.label.padEnd(28)} v15 ${kb(a.gzip).padStart(9)}  ->  v16 ${kb(b.gzip).padStart(9)}  (${delta > 0 ? "+" : ""}${delta}%)`,
  );
}
console.log(
  `\nReport written to ${relative(process.cwd(), join(root, "reports", "bundle-report.md"))}`,
);
