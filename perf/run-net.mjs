// Network transport benchmark orchestrator.
//
// Starts one loopback http server serving a fixed Horizon account payload, then
// drives the same `loadAccount` call through three client configs, each in its
// own process: v15 (axios), v16 default (native fetch), and v16's axios opt-in.
// Writes reports/network-report.md.  Run: npm run net

import { createServer } from "node:http";
import { spawn } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";

const dir = import.meta.dirname;
const root = join(dir, "..");

// Build a valid, complete account payload (valid G... id so the SDK parses it).
const sdk = await import("sdk-v16");
const address = sdk.Keypair.random().publicKey();
const link = (path) => ({ href: `http://127.0.0.1/accounts/${address}${path}` });
const account = {
  _links: {
    self: link(""),
    transactions: link("/transactions{?cursor,limit,order}"),
    operations: link("/operations{?cursor,limit,order}"),
    payments: link("/payments{?cursor,limit,order}"),
    effects: link("/effects{?cursor,limit,order}"),
    offers: link("/offers{?cursor,limit,order}"),
    trades: link("/trades{?cursor,limit,order}"),
    data: link("/data/{key}"),
  },
  id: address,
  account_id: address,
  sequence: "123456789012345",
  subentry_count: 0,
  last_modified_ledger: 1000,
  last_modified_time: "2024-01-01T00:00:00Z",
  thresholds: { low_threshold: 0, med_threshold: 0, high_threshold: 0 },
  flags: { auth_required: false, auth_revocable: false, auth_immutable: false, auth_clawback_enabled: false },
  balances: [
    { balance: "100.0000000", buying_liabilities: "0.0000000", selling_liabilities: "0.0000000", asset_type: "native" },
  ],
  signers: [{ weight: 1, key: address, type: "ed25519_public_key" }],
  data: {},
  num_sponsoring: 0,
  num_sponsored: 0,
  paging_token: address,
};
const body = JSON.stringify(account);

const server = createServer((_req, res) => {
  res.writeHead(200, { "content-type": "application/json" });
  res.end(body);
});
await new Promise((r) => server.listen(0, "127.0.0.1", r));
const port = server.address().port;

const CONFIGS = [
  { key: "v15", label: "v15 (axios)" },
  { key: "v16-fetch", label: "v16 default (fetch)" },
  { key: "v16-axios", label: "v16 axios opt-in" },
];

console.log(`Loopback server on :${port}. Benchmarking transport (each config in its own process)...`);

// Use async spawn (NOT spawnSync): the loopback server lives in this process,
// so the event loop must stay free to answer the child's requests. spawnSync
// would block it and deadlock.
const runChild = (args) =>
  new Promise((resolve) => {
    const p = spawn(process.execPath, args, { cwd: root, stdio: "ignore" });
    const timer = setTimeout(() => {
      p.kill("SIGKILL");
      resolve("timeout");
    }, 30000);
    p.on("error", (err) => {
      clearTimeout(timer);
      resolve(`spawn error: ${err.message}`);
    });
    p.on("close", (code) => {
      clearTimeout(timer);
      resolve(code);
    });
  });

const tmp = mkdtempSync(join(tmpdir(), "sdk-net-"));
const results = {};
try {
  for (const c of CONFIGS) {
    const out = join(tmp, `${c.key}.json`);
    const status = await runChild([join(dir, "net-bench.mjs"), c.key, String(port), address, out]);
    results[c.key] = existsSync(out)
      ? JSON.parse(readFileSync(out, "utf8"))
      : { config: c.key, hz: null, error: `child ${status}` };
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
  server.closeAllConnections?.();
  server.close();
}

// --- Report --------------------------------------------------------------
const fmtHz = (hz) => (hz == null ? "—" : hz >= 1000 ? `${(hz / 1000).toFixed(1)}k` : hz.toFixed(0));
const pct = (a, b) => ((b - a) / a) * 100;
const v15 = results["v15"];
const vf = results["v16-fetch"];
const va = results["v16-axios"];
const wash = (d) => Math.abs(d) < 5;

const lines = [];
lines.push("# Network transport report: `@stellar/stellar-sdk` v16-rc vs v15");
lines.push("");
const today = new Date().toISOString().slice(0, 10);
lines.push(
  `Generated by \`npm run net\` on ${today} (Node ${vf?.node ?? process.version}). The same ` +
    "`Horizon.Server.loadAccount()` call runs against a local loopback server that " +
    "returns a fixed account payload instantly. This isolates the SDK's request-build, " +
    "HTTP-client, and JSON-parse overhead from real network latency. Each config runs " +
    "in its own process.",
);
lines.push("");

// Summary
const parts = [];
if (v15?.hz && vf?.hz) {
  const d = pct(v15.hz, vf.hz);
  parts.push(`v16 default (fetch) is ${wash(d) ? "about the same as" : `${d > 0 ? `${d.toFixed(0)}% faster than` : `${(-d).toFixed(0)}% slower than`}`} v15 (axios)`);
}
if (vf?.hz && va?.hz) {
  const d = pct(va.hz, vf.hz);
  parts.push(`within v16, fetch vs the axios opt-in is ${wash(d) ? "a wash" : `${d > 0 ? `${d.toFixed(0)}% faster` : `${(-d).toFixed(0)}% slower`}`}`);
}
lines.push("## Summary");
lines.push("");
lines.push(
  parts.length
    ? `${parts.join("; ")} on loopback throughput. This gap is **likely connection-reuse behavior** ` +
        "(native fetch/undici pools keep-alive connections by default; the axios client may not) " +
        "rather than per-operation CPU cost — though this benchmark does not toggle keep-alive to " +
        "isolate it. And real-world calls are dominated by network latency, so this rarely decides " +
        "request speed in production."
    : "Benchmark did not produce comparable numbers; see errors below.",
);
lines.push("");

// Table
lines.push("## loadAccount throughput (ops/sec against loopback, higher is better)");
lines.push("");
lines.push("| Client config | ops/sec | ± error | vs v15 |");
lines.push("| --- | --- | --- | --- |");
for (const c of CONFIGS) {
  const r = results[c.key];
  if (!r || r.hz == null) {
    lines.push(`| ${c.label} | — | — | ${r?.error ? `error: ${r.error}` : "—"} |`);
    continue;
  }
  const vs = v15?.hz ? (c.key === "v15" ? "—" : `${pct(v15.hz, r.hz) > 0 ? "+" : ""}${pct(v15.hz, r.hz).toFixed(0)}%`) : "—";
  lines.push(`| ${c.label} | ${fmtHz(r.hz)} | ±${r.rme != null ? r.rme.toFixed(1) : "?"}% | ${vs} |`);
}
lines.push("");
lines.push("## Caveats");
lines.push("");
lines.push(
  "- **Loopback, not the internet.** Wire latency, TLS, DNS, and distance are removed " +
    "on purpose. Real-world `loadAccount` time is dominated by those, not by the client " +
    "library — so this measures client overhead only, and in production the choice of " +
    "fetch vs axios is usually not what determines request speed.",
);
lines.push(
  "- Connection reuse (keep-alive) differs between clients and is part of what this " +
    "captures; it matters more under sustained load than for a single call.",
);
lines.push("- Single machine, single run; treat differences under ±5% as a wash.");
lines.push("");

writeFileSync(join(root, "reports", "network-report.md"), lines.join("\n") + "\n");

// --- Console summary -----------------------------------------------------
console.log("\nTransport (loadAccount, ops/sec vs loopback)\n============================================");
for (const c of CONFIGS) {
  const r = results[c.key];
  console.log(`${c.label.padEnd(24)} ${r?.hz != null ? fmtHz(r.hz).padStart(8) : "failed"}`);
}
console.log(`\nReport written to ${relative(process.cwd(), join(root, "reports", "network-report.md"))}`);
