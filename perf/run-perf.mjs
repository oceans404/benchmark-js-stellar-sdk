// Performance benchmark orchestrator. Runs each SDK version in its OWN process
// (no shared JIT/GC/module cache), collects results, and writes a committed
// report to reports/perf-report.md.  Run: npm run perf

import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";

const dir = import.meta.dirname;
const root = join(dir, "..");
const VERSIONS = ["v15", "v16"];
const COLD_SAMPLES = 30;

const sdkVersion = (v) => {
  try {
    return JSON.parse(readFileSync(join(root, "node_modules", `sdk-${v}`, "package.json"), "utf8")).version;
  } catch {
    return v;
  }
};

const node = process.execPath;
const tmp = mkdtempSync(join(tmpdir(), "sdk-perf-"));

// --- 1. Microbenchmarks (one isolated process per version) ---------------
console.log("Running microbenchmarks (this takes ~30-60s)...");
const micro = {};
for (const v of VERSIONS) {
  const out = join(tmp, `micro-${v}.json`);
  const r = spawnSync(node, [join(dir, "micro.mjs"), v, out], { cwd: root, encoding: "utf8" });
  if (r.status !== 0 || !existsSync(out)) {
    console.error(`micro ${v} failed (status ${r.status}):\n${r.stderr ?? ""}`);
    rmSync(tmp, { recursive: true, force: true });
    process.exit(1);
  }
  micro[v] = JSON.parse(readFileSync(out, "utf8"));
}

// --- 2. Cold start (fresh process per sample) ----------------------------
console.log(`Running cold-start samples (${COLD_SAMPLES} per version)...`);
const percentile = (arr, p) => {
  const s = [...arr].sort((a, b) => a - b);
  return s[Math.min(s.length - 1, Math.floor((p / 100) * s.length))];
};
const median = (arr) => percentile(arr, 50);

const cold = {};
for (const v of VERSIONS) {
  const importMs = [];
  const firstOpMs = [];
  let lastErr = "";
  for (let i = 0; i < COLD_SAMPLES; i++) {
    const r = spawnSync(node, [join(dir, "cold-import.mjs"), v], { cwd: root, encoding: "utf8" });
    if (r.status !== 0 && r.stderr) lastErr = r.stderr;
    try {
      const o = JSON.parse(r.stdout.trim());
      importMs.push(o.importMs);
      firstOpMs.push(o.firstOpMs);
    } catch {
      /* drop a bad sample */
    }
  }
  if (importMs.length < 2) {
    console.error(`cold-import ${v}: only ${importMs.length} valid sample(s); cannot aggregate.\n${lastErr}`);
    rmSync(tmp, { recursive: true, force: true });
    process.exit(1);
  }
  // drop the first sample of each (cold filesystem cache), then aggregate
  cold[v] = {
    importMedian: median(importMs.slice(1)),
    importP90: percentile(importMs.slice(1), 90),
    firstOpMedian: median(firstOpMs.slice(1)),
    samples: importMs.length - 1,
  };
}

// --- 3. Report -----------------------------------------------------------
const pct = (a, b) => ((b - a) / a) * 100;
const fmtHz = (hz) => (hz == null ? "—" : hz >= 1000 ? `${(hz / 1000).toFixed(1)}k` : hz.toFixed(0));
const mark = (deltaPct, higherIsBetter) => {
  const improved = higherIsBetter ? deltaPct > 5 : deltaPct < -5;
  const regressed = higherIsBetter ? deltaPct < -5 : deltaPct > 5;
  return improved ? "✅" : regressed ? "❌" : "◻️";
};

const lines = [];
lines.push("# Performance report: `@stellar/stellar-sdk` v16-rc vs v15");
lines.push("");
const today = new Date().toISOString().slice(0, 10);
lines.push(
  `Generated by \`npm run perf\` on ${today} (Node ${micro.v16?.node ?? process.version}). ` +
    `v15 = ${sdkVersion("v15")}, v16 = ${sdkVersion("v16")}. Each version runs in its ` +
    "own process (no shared JIT/GC/module cache). Single machine, single run — " +
    "directional, not a controlled lab result.",
);
lines.push("");

// Precompute deltas so the summary can lead.
const byName = (set) => Object.fromEntries(set.results.map((r) => [r.name, r]));
const m15 = byName(micro.v15);
const m16 = byName(micro.v16);
const names = micro.v16.results.map((r) => r.name);
const importD = pct(cold.v15.importMedian, cold.v16.importMedian);
const firstOpD = pct(cold.v15.firstOpMedian, cold.v16.firstOpMedian);
const deltas = names
  .filter((n) => m15[n]?.hz != null && m16[n]?.hz != null)
  .map((n) => ({ name: n, d: pct(m15[n].hz, m16[n].hz) }));
const regressions = deltas.filter((x) => mark(x.d, true) === "❌");
const wins = deltas.filter((x) => mark(x.d, true) === "✅");

lines.push("## Summary");
lines.push("");
lines.push(
  `v16 imports ${importD < 0 ? `${(-importD).toFixed(0)}% faster` : `${importD.toFixed(0)}% slower`} ` +
    `(cold, median). Hot paths: ${wins.length} faster, ${regressions.length} slower (>5% threshold). ` +
    (regressions.length
      ? `Apparent regressions (single run — confirm before trusting, see ± column): ${regressions.map((r) => `${r.name} ${r.d.toFixed(0)}%`).join(", ")}.`
      : "No regressions."),
);
lines.push("");

// Microbenchmark table
lines.push("## Hot-path throughput (ops/sec, higher is better)");
lines.push("");
lines.push("| Operation | v15 | v16 | Δ | ± (v16) | |");
lines.push("| --- | --- | --- | --- | --- | --- |");
for (const name of names) {
  const a = m15[name];
  const b = m16[name];
  if (!a || a.hz == null || b.hz == null) {
    lines.push(`| ${name} | ${a ? fmtHz(a.hz) : "n/a"} | ${fmtHz(b?.hz)} | — | — | |`);
    continue;
  }
  const d = pct(a.hz, b.hz);
  const err = b.rme != null ? `±${b.rme.toFixed(1)}%` : "—";
  lines.push(`| ${name} | ${fmtHz(a.hz)} | ${fmtHz(b.hz)} | ${d > 0 ? "+" : ""}${d.toFixed(0)}% | ${err} | ${mark(d, true)} |`);
}
lines.push("");

// Cold start table
lines.push("## Cold start (milliseconds, lower is better)");
lines.push("");
lines.push("| Metric | v15 | v16 | Δ |");
lines.push("| --- | --- | --- | --- |");
lines.push(
  `| Import (median) | ${cold.v15.importMedian.toFixed(1)} | ${cold.v16.importMedian.toFixed(1)} | ${importD > 0 ? "+" : ""}${importD.toFixed(0)}% ${mark(importD, false)} |`,
);
lines.push(
  `| Import (p90) | ${cold.v15.importP90.toFixed(1)} | ${cold.v16.importP90.toFixed(1)} | ${pct(cold.v15.importP90, cold.v16.importP90) > 0 ? "+" : ""}${pct(cold.v15.importP90, cold.v16.importP90).toFixed(0)}% ${mark(pct(cold.v15.importP90, cold.v16.importP90), false)} |`,
);
lines.push(
  `| Time to first op (median) | ${cold.v15.firstOpMedian.toFixed(1)} | ${cold.v16.firstOpMedian.toFixed(1)} | ${firstOpD > 0 ? "+" : ""}${firstOpD.toFixed(0)}% ${mark(firstOpD, false)} |`,
);
lines.push("");
lines.push("(Negative Δ = v16 is faster to load.)");
lines.push("");

// Regressions callout
lines.push("## Regressions");
lines.push("");
if (regressions.length === 0) {
  lines.push("None over the 5% threshold in this run.");
} else {
  lines.push(
    "Single run, so treat these as **provisional** — confirm with repeated runs and " +
      "check the ± error column before calling them definitive regressions.",
  );
  lines.push("");
  for (const r of regressions) {
    const err = m16[r.name]?.rme;
    lines.push(`- **${r.name}**: ${r.d.toFixed(0)}% slower in v16${err != null ? ` (±${err.toFixed(1)}%)` : ""}.`);
  }
}
lines.push("");
lines.push("## Caveats");
lines.push("");
lines.push(
  "- **Signing:** v16 signs via pure-JS `@noble/ed25519`. These numbers compare " +
    "against v15's pure-JS path. If a v15 deployment had the native `sodium-native` " +
    "addon installed (the old `FastSigning`), that native path is far faster than " +
    "either, and v16 would be a regression against it. Report sign/verify with that " +
    "asterisk.",
);
lines.push(
  "- Single machine, single run. For a publishable number, run on an idle/pinned " +
    "machine and repeat. Treat <±5% as a wash.",
);
lines.push("- These are for an RC (`16.0.0-rc.1`); re-run on stable v16.");
const skipped16 = micro.v16.skipped ?? [];
if (skipped16.length) {
  lines.push(
    `- Skipped in v16 (symbol unavailable): ${skipped16.map((s) => s.name).join(", ")}.`,
  );
}
lines.push("");

writeFileSync(join(root, "reports", "perf-report.md"), lines.join("\n") + "\n");

// --- Console summary -----------------------------------------------------
console.log("\nPerformance summary (ops/sec)\n=============================");
for (const name of names) {
  const a = m15[name];
  const b = m16[name];
  if (!a || a.hz == null || b.hz == null) continue;
  const d = pct(a.hz, b.hz);
  console.log(
    `${name.padEnd(20)} v15 ${fmtHz(a.hz).padStart(8)}  ->  v16 ${fmtHz(b.hz).padStart(8)}  (${d > 0 ? "+" : ""}${d.toFixed(0)}%)`,
  );
}
console.log(
  `\nCold import (median): v15 ${cold.v15.importMedian.toFixed(1)}ms -> v16 ${cold.v16.importMedian.toFixed(1)}ms (${importD > 0 ? "+" : ""}${importD.toFixed(0)}%)`,
);
console.log(`Report written to ${relative(process.cwd(), join(root, "reports", "perf-report.md"))}`);
if (regressions.length) {
  console.log(`\n⚠ Regressions (>5% slower in v16): ${regressions.map((r) => r.name).join(", ")}`);
}

rmSync(tmp, { recursive: true, force: true });
